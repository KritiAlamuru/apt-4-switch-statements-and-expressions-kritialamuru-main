import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.file.Files;
import java.nio.file.Path;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Nested;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

/**
 * Tests for OrderProcessor. Run with the "Run JUnit Tests" task or the
 * VS Code Testing panel. Do not edit this file.
 */
class OrderProcessorTest {

    private static final double DELTA = 0.001;
    private static final Path SOURCE = Path.of("src/main/java/OrderProcessor.java");

    // ------------------------------------------------------------------
    // Task 1: traditional switch
    // ------------------------------------------------------------------
    @Nested
    @DisplayName("Task 1: calculateShippingFee (traditional switch)")
    class Task1 {

        @ParameterizedTest(name = "{0}, {1} lb -> {2}")
        @CsvSource({
            "STANDARD,  4.0,  5.00",
            "STANDARD, 20.0,  5.00",
            "STANDARD, 20.5, 13.00",
            "SAVER,     1.0,  5.00",
            "SAVER,    30.0, 13.00",
            "EXPRESS,   3.0, 15.00",
            "EXPRESS,  25.0, 23.00",
            "OVERNIGHT, 3.0, 25.00",
            "OVERNIGHT,50.0, 25.00",
            "SAME_DAY,  3.0, 35.00",
            "SAME_DAY, 50.0, 35.00",
        })
        void validTiers(String tier, double weight, double expected) {
            assertEquals(expected, OrderProcessor.calculateShippingFee(tier, weight), DELTA);
        }

        @ParameterizedTest(name = "{0} -> {2}")
        @CsvSource({
            "standard,  4.0,  5.00",
            "Express,   4.0, 15.00",
            "same_day,  4.0, 35.00",
        })
        void tierIsCaseInsensitive(String tier, double weight, double expected) {
            assertEquals(expected, OrderProcessor.calculateShippingFee(tier, weight), DELTA);
        }

        @ParameterizedTest(name = "{0}, {1} lb -> -1.0")
        @CsvSource({
            "DRONE,     4.0",
            "TELEPORT, 30.0",
            "'',        4.0",
        })
        void unknownTier(String tier, double weight) {
            assertEquals(-1.0, OrderProcessor.calculateShippingFee(tier, weight), DELTA);
        }

        @Test
        @DisplayName("null tier -> -1.0")
        void nullTier() {
            assertEquals(-1.0, OrderProcessor.calculateShippingFee(null, 4.0), DELTA);
        }
    }

    // ------------------------------------------------------------------
    // Task 2: switch expression with yield
    // ------------------------------------------------------------------
    @Nested
    @DisplayName("Task 2: calculateDeliveryDays (switch expression)")
    class Task2 {

        @ParameterizedTest(name = "{0}, remote={1} -> {2}")
        @CsvSource({
            "SAME_DAY,  false,  0",
            "SAME_DAY,  true,  -1",
            "OVERNIGHT, false,  1",
            "OVERNIGHT, true,   4",
            "EXPRESS,   false,  2",
            "EXPRESS,   true,   5",
            "STANDARD,  false,  5",
            "STANDARD,  true,   8",
            "SAVER,     false,  5",
            "SAVER,     true,   8",
            "CUSTOM,    false, 10",
            "CUSTOM,    true,  13",
            "overnight, false,  1",
            "Custom,    true,  13",
        })
        void validTiers(String tier, boolean remote, int expected) {
            int actual = captureOutput(() -> OrderProcessor.calculateDeliveryDays(tier, remote)).value;
            assertEquals(expected, actual);
        }

        @ParameterizedTest(name = "{0}, remote={1} -> -1")
        @CsvSource({
            "DRONE, false",
            "DRONE, true",
            "'',    true",
        })
        void unknownTier(String tier, boolean remote) {
            assertEquals(-1, OrderProcessor.calculateDeliveryDays(tier, remote));
        }

        @Test
        @DisplayName("null tier -> -1")
        void nullTier() {
            assertEquals(-1, OrderProcessor.calculateDeliveryDays(null, false));
            assertEquals(-1, OrderProcessor.calculateDeliveryDays(null, true));
        }

        @Test
        @DisplayName("CUSTOM logs the courier message")
        void customLogsMessage() {
            String out = captureOutput(() -> OrderProcessor.calculateDeliveryDays("CUSTOM", false)).output;
            assertTrue(out.contains("Calculating custom courier rates..."),
                    "Expected the CUSTOM message to be printed, but output was: \"" + out.trim() + "\"");
        }

        @Test
        @DisplayName("Only CUSTOM logs a message")
        void otherTiersAreQuiet() {
            String out = captureOutput(() -> OrderProcessor.calculateDeliveryDays("EXPRESS", false)).output;
            assertFalse(out.contains("Calculating custom courier rates..."),
                    "EXPRESS should not print the CUSTOM message");
        }

        @Test
        @DisplayName("Uses a switch expression with -> and yield")
        void usesModernSwitch() throws IOException {
            String body = methodBody("calculateDeliveryDays");
            assertTrue(body.contains("switch"), "Expected a switch");
            assertTrue(body.contains("->"), "Expected arrow (->) cases");
            assertTrue(body.matches("(?s).*\\byield\\b.*"), "Expected at least one yield");
            assertFalse(body.matches("(?s).*\\bbreak\\b.*"), "A switch expression should not need break");
        }
    }

    // ------------------------------------------------------------------
    // Task 3: rewrite Task 1 as a switch expression
    // ------------------------------------------------------------------
    @Nested
    @DisplayName("Task 3: calculateShippingFeeModern (switch expression)")
    class Task3 {

        @ParameterizedTest(name = "{0}, {1} lb -> {2}")
        @CsvSource({
            "STANDARD,  4.0,  5.00",
            "STANDARD, 20.0,  5.00",
            "STANDARD, 20.5, 13.00",
            "SAVER,    30.0, 13.00",
            "EXPRESS,   3.0, 15.00",
            "EXPRESS,  25.0, 23.00",
            "OVERNIGHT,50.0, 25.00",
            "SAME_DAY,  3.0, 35.00",
            "SAME_DAY, 50.0, 35.00",
            "express,  25.0, 23.00",
            "DRONE,     4.0, -1.00",
            "DRONE,    30.0, -1.00",
        })
        void matchesFeeRules(String tier, double weight, double expected) {
            assertEquals(expected, OrderProcessor.calculateShippingFeeModern(tier, weight), DELTA);
        }

        @Test
        @DisplayName("null tier -> -1.0")
        void nullTier() {
            assertEquals(-1.0, OrderProcessor.calculateShippingFeeModern(null, 4.0), DELTA);
        }

        @Test
        @DisplayName("Uses a switch expression with no break or fall-through")
        void usesModernSwitch() throws IOException {
            String body = methodBody("calculateShippingFeeModern");
            assertTrue(body.contains("switch"), "Expected a switch");
            assertTrue(body.contains("->"), "Expected arrow (->) cases");
            assertFalse(body.matches("(?s).*\\bbreak\\b.*"), "Do not use break");
            String label = "(\"[^\"]*\"|\\w+)";
            assertFalse(body.matches("(?s).*\\bcase\\s+" + label + "(\\s*,\\s*" + label + ")*\\s*:.*")
                    || body.matches("(?s).*\\bdefault\\s*:.*"), "Do not use colon-style case labels");
        }
    }

    // ------------------------------------------------------------------
    // Helpers
    // ------------------------------------------------------------------

    private record Captured<T>(T value, String output) { }

    private static <T> Captured<T> captureOutput(java.util.function.Supplier<T> action) {
        PrintStream original = System.out;
        ByteArrayOutputStream buffer = new ByteArrayOutputStream();
        System.setOut(new PrintStream(buffer, true));
        try {
            T value = action.get();
            return new Captured<>(value, buffer.toString());
        } finally {
            System.setOut(original);
        }
    }

    /** Returns the source of the named method's body, with comments removed. */
    private static String methodBody(String name) throws IOException {
        String src = Files.readString(SOURCE)
                .replaceAll("(?s)/\\*.*?\\*/", "")
                .replaceAll("//[^\\n]*", "");
        int start = src.indexOf(" " + name + "(");
        assertTrue(start >= 0, "Could not find method " + name);
        int open = src.indexOf('{', start);
        int depth = 0;
        for (int i = open; i < src.length(); i++) {
            char c = src.charAt(i);
            if (c == '{') {
                depth++;
            } else if (c == '}' && --depth == 0) {
                return src.substring(open, i + 1);
            }
        }
        throw new AssertionError("Could not parse method " + name);
    }
}
